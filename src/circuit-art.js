const CLASSIC_ART_CACHE = {};

function classicHash(text) {
  let hash = 2166136261;
  for (let i = 0; i < text.length; i += 1) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function classicCircuitArt(track) {
  const id = track?.id || 'classic';
  if (CLASSIC_ART_CACHE[id]) return CLASSIC_ART_CACHE[id];
  let seed = classicHash(id);
  const random = () => {
    seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
    return seed / 4294967296;
  };
  const count = 12 + (classicHash(id) % 3) * 2;
  const points = [];
  for (let i = 0; i < count; i += 1) {
    const angle = (i / count) * Math.PI * 2 - Math.PI / 2 + (random() - 0.5) * 0.2;
    const radius = i % 4 === 0
      ? 118 + random() * 46
      : i % 4 === 2
        ? 52 + random() * 28
        : 78 + random() * 50;
    points.push({
      x: 300 + Math.cos(angle) * radius * 1.36 + (random() - 0.5) * 16,
      y: 160 + Math.sin(angle) * radius * 0.88 + (random() - 0.5) * 12
    });
  }
  const clampPoint = (point) => ({
    x: Math.max(34, Math.min(566, point.x)),
    y: Math.max(28, Math.min(292, point.y))
  });
  const safe = points.map(clampPoint);
  let path = `M ${safe[0].x.toFixed(1)} ${safe[0].y.toFixed(1)}`;
  for (let i = 0; i < safe.length; i += 1) {
    const p0 = safe[(i - 1 + safe.length) % safe.length];
    const p1 = safe[i];
    const p2 = safe[(i + 1) % safe.length];
    const p3 = safe[(i + 2) % safe.length];
    const c1 = { x: p1.x + (p2.x - p0.x) / 9, y: p1.y + (p2.y - p0.y) / 9 };
    const c2 = { x: p2.x - (p3.x - p1.x) / 9, y: p2.y - (p3.y - p1.y) / 9 };
    path += ` C ${c1.x.toFixed(1)} ${c1.y.toFixed(1)}, ${c2.x.toFixed(1)} ${c2.y.toFixed(1)}, ${p2.x.toFixed(1)} ${p2.y.toFixed(1)}`;
  }
  path += ' Z';
  CLASSIC_ART_CACHE[id] = { path, start: [safe[0].x, safe[0].y] };
  return CLASSIC_ART_CACHE[id];
}
